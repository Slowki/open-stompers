"""Generate static nalgebra link transforms for hardware adapter crates.

The generator reads LinkForge robot definitions and renders Rust modules from
the Jinja templates in ``templates/link_transforms``. Generated code does not
look up joints or links in a map. A helper converts a joint-position vector
into Rerun ``Transform3D`` messages so a link mesh can be logged on the
kinematic tree.
"""

