def build(variant: MicroduckVariant) -> Robot:
    """Build a validated Microduck LinkForge model."""
    try:
        links = _LINKS[variant]
        joints = _JOINTS[variant]
    except KeyError:
        available = ", ".join(_LINKS)
        raise KeyError(f"Unknown Microduck variant '{variant}'. Available: {available}") from None
    return build_robot(
        variant,
        links,
        joints,
        mesh_resource=lambda filename: assets.get_cache_relative_path(variant, filename),
        materials=MATERIALS,
    )


def ensure_meshes(variant: MicroduckVariant | None = None) -> list[Path]:
    """Download missing Microduck mesh assets for one or all variants."""
    return assets.ensure_meshes(variant)
